import assert from 'node:assert/strict';
import {
  describePricingChange,
  matchTier,
  monthlyCost,
  pricingToCarryForward,
  readPricingRequest,
  tierChoices,
} from '../src/services/chatPricing';
import { buildModificationPrompt } from '../src/services/modificationPrompt';
import { buildArchitectureGenerationSystemPrompt } from '../src/services/architectureGenerationContract';
import type { NodePricingConfig, PricingTier } from '../src/types/pricing';

const tier = (name: string, skuName: string, monthlyPrice: number): PricingTier => ({ name, skuName, monthlyPrice, unit: 'per unit/month' });
const pricing = (t: string, estimatedCost: number, quantity = 1, extra: Partial<NodePricingConfig> = {}): NodePricingConfig => ({
  estimatedCost, tier: t, skuName: t, quantity, region: 'eastus2', unit: 'per unit/month', lastUpdated: '2026-10-26T00:00:00Z', isCustom: false, ...extra,
});

// ── readPricingRequest ─────────────────────────────────────────────────────
assert.equal(readPricingRequest(undefined), null);
assert.equal(readPricingRequest({}), null, 'An empty pricing object is not a request');
assert.equal(readPricingRequest({ tier: '  ' }), null);
assert.deepEqual(readPricingRequest({ tier: ' Standard v2 ' }), { tier: 'Standard v2' });
assert.deepEqual(readPricingRequest({ quantity: '3' }), { quantity: 3 });
assert.deepEqual(readPricingRequest({ tier: 'P1v3', quantity: 2.6 }), { tier: 'P1v3', quantity: 3 });
assert.deepEqual(readPricingRequest({ quantity: 0 }), { quantity: 1 }, 'Quantity is at least 1');
assert.deepEqual(readPricingRequest({ quantity: 1e9 }), { quantity: 1000 }, 'Quantity is capped');
assert.equal(readPricingRequest({ quantity: 'many' }), null);

// ── matchTier: API Management Standard vs Standard v2 must not collide ─────
const apim = [
  tier('Consumption', 'Consumption', 0), tier('Developer', 'Developer', 49), tier('Basic', 'Basic', 150),
  tier('Basic v2', 'Basic v2', 158), tier('Standard', 'Standard', 700), tier('Standard v2', 'Standard v2', 700.3),
  tier('Premium', 'Premium', 2802), tier('Premium v2', 'Premium v2', 2801),
];
assert.equal(matchTier(apim, 'Standard')?.name, 'Standard');
assert.equal(matchTier(apim, 'standard v2')?.name, 'Standard v2');
assert.equal(matchTier(apim, 'StandardV2')?.name, 'Standard v2');
assert.equal(matchTier(apim, 'Premium')?.name, 'Premium');
assert.equal(matchTier(apim, 'Gold'), undefined, 'Unknown tiers are not guessed');
assert.equal(matchTier(apim, ''), undefined);
const appService = [tier('B1 (Basic)', 'B1', 13), tier('S1 (Standard)', 'S1', 69.35), tier('P1v3 (Premium v3)', 'P1v3', 113.15)];
assert.equal(matchTier(appService, 'p1v3')?.skuName, 'P1v3');
assert.equal(matchTier(appService, 'S1')?.skuName, 'S1');
assert.deepEqual(tierChoices(appService), ['B1', 'S1', 'P1v3']);

// ── pricingToCarryForward: keep what the user chose ────────────────────────
const node = (id: string, label: string, p: NodePricingConfig | null) => ({ id, type: 'azureNode', data: { label, pricing: p } });
const previous = [
  node('app', 'App Service', pricing('I6v4', 9918.66, 2)),
  node('sql', 'SQL Database', pricing('S1', 29.03)),
  node('kv', 'Key Vault', pricing('Standard', 1.5, 1, { isCustom: true, customPrice: 1.5 })),
  { id: 'grp', type: 'groupNode', data: { label: 'Data' } },
];
let carried = pricingToCarryForward(previous, [
  { id: 'app', name: 'App Service' },
  { id: 'sql-2', name: 'SQL Database' },          // id regenerated by the AI: match by name
  { id: 'kv', name: 'Key Vault' },
  { id: 'redis', name: 'Azure Cache for Redis' }, // new service: no carried pricing
]);
assert.equal(carried.get('app')?.tier, 'I6v4', 'A manual tier survives a refinement');
assert.equal(carried.get('app')?.quantity, 2, 'A manual instance count survives a refinement');
assert.equal(carried.get('sql-2')?.tier, 'S1', 'Regenerated ids still keep pricing by name');
assert.equal(carried.get('kv')?.isCustom, true, 'A custom price survives a refinement');
assert.equal(carried.has('redis'), false, 'New services get fresh catalog pricing');

carried = pricingToCarryForward(previous, [
  { id: 'app', name: 'Azure Container Apps' },     // same id, different service: replaced
  { id: 'app-2', name: 'App Service' },
  { id: 'app-3', name: 'App Service' },            // second instance: fresh pricing
]);
assert.equal(carried.has('app'), false, 'A replaced service does not inherit the old pricing');
assert.equal(carried.get('app-2')?.tier, 'I6v4');
assert.equal(carried.has('app-3'), false, 'Each previous node is carried at most once');
assert.equal(pricingToCarryForward([], [{ id: 'a', name: 'App Service' }]).size, 0);

// ── change review lines ────────────────────────────────────────────────────
assert.equal(monthlyCost(pricing('S1', 69.35, 2)), 138.7);
assert.equal(
  describePricingChange({ serviceId: 'apim', serviceName: 'API Management', status: 'applied', fromTier: 'Developer', toTier: 'Standard v2', fromQuantity: 1, toQuantity: 1, monthlyDelta: 651.3 }),
  '- API Management: Developer → Standard v2 · +$651.30/mo.',
);
assert.equal(
  describePricingChange({ serviceId: 'app', serviceName: 'App Service', status: 'applied', fromTier: 'S1', toTier: 'S1', fromQuantity: 1, toQuantity: 3, monthlyDelta: 138.7 }),
  '- App Service: 1 → 3 instances · +$138.70/mo.',
);
assert.match(
  describePricingChange({ serviceId: 'app', serviceName: 'App Service', status: 'applied', fromTier: 'P1v3', toTier: 'S1', fromQuantity: 2, toQuantity: 1, monthlyDelta: -157 }),
  /P1v3 → S1, 2 → 1 instance · −\$157\.00\/mo\.$/,
);
assert.match(
  describePricingChange({ serviceId: 'apim', serviceName: 'API Management', status: 'unknown-tier', requestedTier: 'Gold', validTiers: ['Developer', 'Standard v2'] }),
  /tier "Gold" isn't in the price catalog.*Available tiers: Developer, Standard v2\./,
);
assert.equal(
  describePricingChange({ serviceId: 'apim', serviceName: 'API Management', status: 'applied', fromTier: 'Developer', toTier: 'Developer', fromQuantity: 1, toQuantity: 1, monthlyDelta: 0 }),
  '- API Management: Developer tier, as requested.',
  'A new service added at its named tier is reported plainly',
);
assert.match(describePricingChange({ serviceId: 's', serviceName: 'Storage Account', status: 'not-tiered' }), /priced by usage/);
assert.match(describePricingChange({ serviceId: 'k', serviceName: 'Key Vault', status: 'custom-price-kept' }), /kept your custom price/);

// ── prompts carry the contract ─────────────────────────────────────────────
const prompt = buildModificationPrompt({ nodes: previous, edges: [], architectureName: 'Clinic' }, 'Make API Management Standard v2');
assert.match(prompt, /Current pricing tiers: App Service: I6v4 x2; SQL Database: S1; Key Vault: custom price/);
assert.match(prompt, /Services: App Service, SQL Database, Key Vault/, 'Service names stay clean for icon matching');
assert.match(prompt, /return "pricing": \{ "tier", "quantity" \} on that service only/);
assert.match(buildArchitectureGenerationSystemPrompt(), /"pricing": \{ "tier": "optional", "quantity": 1 \}/);
assert.match(buildArchitectureGenerationSystemPrompt(), /Add "pricing" to a service ONLY when the user's request names a pricing tier/);

console.log('Chat pricing tests passed.');
